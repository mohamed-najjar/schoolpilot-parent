// No raw invitation secret belongs in OAuth state, URLs sent to a server or storage.
export const invitationPattern =
  /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}\.[A-Za-z0-9_-]{43}$/;
export function invitationValue(value: unknown): value is string {
  return typeof value === "string" && invitationPattern.test(value);
}
export function schoolValue(value: unknown): value is string {
  return (
    typeof value === "string" &&
    /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/.test(value)
  );
}
